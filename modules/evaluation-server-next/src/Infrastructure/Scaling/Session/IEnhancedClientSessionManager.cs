using Infrastructure.Connections;
using Infrastructure.Protocol;
using Infrastructure.Scaling.Types;

namespace Infrastructure.Scaling.Session;

/// <summary>
/// Enhanced session manager that handles both explicit identify messages and automatic legacy client identification
/// </summary>
public interface IEnhancedClientSessionManager : IClientSessionManager
{
    /// <summary>
    /// Automatically handle a new connection, creating a session if one doesn't exist.
    /// For legacy clients, this generates a deterministic identifier and creates/resumes their session.
    /// For modern clients, this prepares for an incoming identify message.
    /// </summary>
    /// <param name="connectionId">The connection ID</param>
    /// <param name="connectionContext">The connection context</param>
    /// <returns>Auto-identify response containing session information</returns>
    Task<AutoIdentifyResponse> HandleConnectionAsync(string connectionId, ConnectionContext connectionContext);
    
    /// <summary>
    /// Check if a connection has been automatically identified (legacy client)
    /// </summary>
    /// <param name="connectionId">The connection ID</param>
    /// <returns>True if automatically identified</returns>
    bool IsAutoIdentified(string connectionId);
    
    /// <summary>
    /// Get the client ID for a connection (works for both legacy and modern clients)
    /// </summary>
    /// <param name="connectionId">The connection ID</param>
    /// <returns>Client ID if found, null otherwise</returns>
    string? GetClientId(string connectionId);
}

/// <summary>
/// Response from automatic connection handling
/// </summary>
public class AutoIdentifyResponse
{
    public bool Success { get; set; }
    public string? ClientId { get; set; }
    public bool SessionResumed { get; set; }
    public List<string> RestoredChannels { get; set; } = new();
    public bool AutoGenerated { get; set; }
    public string? Error { get; set; }
    public SessionInfo? Session { get; set; }
} 