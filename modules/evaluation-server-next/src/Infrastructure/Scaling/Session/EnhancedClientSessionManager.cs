using System.Collections.Concurrent;
using Domain.EndUsers;
using Infrastructure.Connections;
using Infrastructure.Protocol;
using Infrastructure.Scaling.Types;
using Microsoft.Extensions.Logging;

namespace Infrastructure.Scaling.Session;

/// <summary>
/// Enhanced session manager that provides seamless session management for both legacy and modern clients
/// </summary>
public class EnhancedClientSessionManager : IEnhancedClientSessionManager
{
    private readonly IClientSessionManager _baseSessionManager;
    private readonly ILegacyClientIdentifierGenerator _identifierGenerator;
    private readonly ILogger<EnhancedClientSessionManager> _logger;
    
    // Track auto-identified connections
    private readonly ConcurrentDictionary<string, string> _autoIdentifiedConnections = new();

    public EnhancedClientSessionManager(
        IClientSessionManager baseSessionManager,
        ILegacyClientIdentifierGenerator identifierGenerator,
        ILogger<EnhancedClientSessionManager> logger)
    {
        _baseSessionManager = baseSessionManager;
        _identifierGenerator = identifierGenerator;
        _logger = logger;
    }

    public async Task<AutoIdentifyResponse> HandleConnectionAsync(string connectionId, ConnectionContext connectionContext)
    {
        try
        {
            // Generate deterministic client ID from connection context
            var clientId = _identifierGenerator.GenerateClientId(connectionContext);
            
            // Create identify message from connection context
            var identifyMessage = CreateIdentifyMessage(connectionContext, clientId);
            
            // Use base session manager to handle identification
            var response = await _baseSessionManager.HandleClientIdentifyAsync(connectionId, identifyMessage);
            
            if (response.Success)
            {
                // Track this as auto-identified
                _autoIdentifiedConnections[connectionId] = clientId;
                
                _logger.LogInformation("Auto-identified legacy client {ClientId} on connection {ConnectionId}, session resumed: {SessionResumed}", 
                    clientId, connectionId, response.SessionResumed);
                
                return new AutoIdentifyResponse
                {
                    Success = true,
                    ClientId = response.ClientId,
                    SessionResumed = response.SessionResumed,
                    RestoredChannels = response.RestoredChannels,
                    AutoGenerated = true,
                    Session = response.Session
                };
            }
            else
            {
                _logger.LogWarning("Failed to auto-identify legacy client on connection {ConnectionId}: {Error}", 
                    connectionId, response.Error);
                
                return new AutoIdentifyResponse
                {
                    Success = false,
                    Error = response.Error,
                    AutoGenerated = true
                };
            }
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error handling connection auto-identification for {ConnectionId}", connectionId);
            return new AutoIdentifyResponse
            {
                Success = false,
                Error = "Failed to auto-identify connection",
                AutoGenerated = true
            };
        }
    }

    public bool IsAutoIdentified(string connectionId)
    {
        return _autoIdentifiedConnections.ContainsKey(connectionId);
    }

    public string? GetClientId(string connectionId)
    {
        return _autoIdentifiedConnections.TryGetValue(connectionId, out var clientId) ? clientId : null;
    }

    #region IClientSessionManager Delegation

    public async Task<ClientIdentifyResponse> HandleClientIdentifyAsync(string connectionId, ClientIdentifyMessage identifyMessage)
    {
        // For explicit identify messages, use base manager directly
        var response = await _baseSessionManager.HandleClientIdentifyAsync(connectionId, identifyMessage);
        
        if (response.Success && response.ClientId != null)
        {
            // Remove from auto-identified tracking since this is now explicitly identified
            _autoIdentifiedConnections.TryRemove(connectionId, out _);
        }
        
        return response;
    }

    public async Task<ClientSession?> GetSessionByConnectionAsync(string connectionId)
    {
        return await _baseSessionManager.GetSessionByConnectionAsync(connectionId);
    }

    public async Task<bool> AddChannelSubscriptionAsync(string connectionId, string channel)
    {
        return await _baseSessionManager.AddChannelSubscriptionAsync(connectionId, channel);
    }

    public async Task<bool> RemoveChannelSubscriptionAsync(string connectionId, string channel)
    {
        return await _baseSessionManager.RemoveChannelSubscriptionAsync(connectionId, channel);
    }

    public async Task HandleClientDisconnectAsync(string connectionId)
    {
        // Clean up auto-identification tracking
        _autoIdentifiedConnections.TryRemove(connectionId, out _);
        
        await _baseSessionManager.HandleClientDisconnectAsync(connectionId);
    }

    public async Task<bool> SendToClientAsync(string clientId, string message)
    {
        return await _baseSessionManager.SendToClientAsync(clientId, message);
    }

    public async Task<IEnumerable<ClientSession>> GetActiveSessionsAsync()
    {
        return await _baseSessionManager.GetActiveSessionsAsync();
    }

    #endregion

    #region Private Methods

    private ClientIdentifyMessage CreateIdentifyMessage(ConnectionContext connectionContext, string clientId)
    {
        var user = _identifierGenerator.ExtractUser(connectionContext);
        var secret = connectionContext.Connection?.Secret;
        
        return new ClientIdentifyMessage
        {
            ClientId = clientId, // Pre-generated deterministic ID
            User = user ?? new EndUser
            {
                KeyId = $"auto-{secret?.Type ?? "unknown"}",
                Name = $"Auto-identified {secret?.Type ?? "unknown"} client",
                CustomizedProperties = Array.Empty<CustomizedProperty>()
            },
            EnvId = secret?.EnvId ?? Guid.Empty
        };
    }

    #endregion
} 