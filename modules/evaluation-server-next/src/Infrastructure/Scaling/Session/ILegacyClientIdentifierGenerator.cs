using Domain.EndUsers;
using Domain.Shared;
using Infrastructure.Connections;

namespace Infrastructure.Scaling.Session;

/// <summary>
/// Generates deterministic client identifiers for legacy clients that don't send explicit identify messages.
/// This enables automatic session management without requiring client code changes.
/// </summary>
public interface ILegacyClientIdentifierGenerator
{
    /// <summary>
    /// Generate a deterministic client identifier from connection context.
    /// This identifier will be consistent across reconnections from the same logical client.
    /// </summary>
    /// <param name="connectionContext">The connection context containing authentication and client info</param>
    /// <returns>A deterministic client identifier that can be used for session management</returns>
    string GenerateClientId(ConnectionContext connectionContext);
    
    /// <summary>
    /// Generate a client identifier from individual components (for testing/debugging)
    /// </summary>
    /// <param name="secret">The authentication secret</param>
    /// <param name="user">The end user (for client-side SDKs)</param>
    /// <param name="connectionType">The connection type</param>
    /// <returns>A deterministic client identifier</returns>
    string GenerateClientId(Secret secret, EndUser? user = null, string? connectionType = null);
    
    /// <summary>
    /// Extract user information from connection context for identifier generation
    /// </summary>
    /// <param name="connectionContext">The connection context</param>
    /// <returns>User information if available, null otherwise</returns>
    EndUser? ExtractUser(ConnectionContext connectionContext);
    
    /// <summary>
    /// Check if a client identifier was generated by this service (vs. explicit identify message)
    /// </summary>
    /// <param name="clientId">The client identifier to check</param>
    /// <returns>True if this is a legacy-generated identifier</returns>
    bool IsLegacyGeneratedId(string clientId);
} 