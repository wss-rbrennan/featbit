    [Fact]
    public async Task HandleConnectionAsync_AutoIdentification_Success()
    {
        // Arrange
        var connectionId = "conn-123";
        var clientId = "legacy:client:abc123:env:def456";
        var connectionContext = CreateMockConnectionContext("client");

        _mockIdentifierGenerator
            .Setup(x => x.GenerateClientId(It.IsAny<ConnectionContext>()))
            .Returns(clientId);

        _mockBaseManager
            .Setup(x => x.HandleClientIdentifyAsync(connectionId, It.IsAny<ClientIdentifyMessage>()))
            .ReturnsAsync(new ClientIdentifyResponse 
            { 
                Success = true, 
                ClientId = clientId,
                SessionResumed = false,
                RestoredChannels = new List<string>()
            });

        // Act
        var result = await _enhancedManager.HandleConnectionAsync(connectionId, connectionContext);

        // Assert
        Assert.True(result.Success);
        Assert.Equal(clientId, result.ClientId);
        Assert.True(result.AutoGenerated);
        Assert.False(result.SessionResumed);
        Assert.True(_enhancedManager.IsAutoIdentified(connectionId));
    }

