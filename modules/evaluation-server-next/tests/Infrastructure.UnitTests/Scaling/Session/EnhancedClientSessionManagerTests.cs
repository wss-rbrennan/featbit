    [Fact]
    public async Task HandleClientIdentifyAsync_ExplicitIdentify_OverridesAutoIdentification()
    {
        // Arrange
        var connectionId = "conn-123";
        var autoClientId = "legacy:client:auto123:env:def456";
        var explicitClientId = "explicit-client-id";
        
        // First auto-identify
        var connectionContext = CreateMockConnectionContext("client");
        _mockIdentifierGenerator
            .Setup(x => x.GenerateClientId(It.IsAny<ConnectionContext>()))
            .Returns(autoClientId);

        _mockBaseManager
            .Setup(x => x.HandleClientIdentifyAsync(connectionId, It.IsAny<ClientIdentifyMessage>()))
            .ReturnsAsync(new ClientIdentifyResponse { Success = true, ClientId = autoClientId });

        await _enhancedManager.HandleConnectionAsync(connectionId, connectionContext);
        Assert.True(_enhancedManager.IsAutoIdentified(connectionId));

        // Setup explicit identify
        var explicitMessage = new ClientIdentifyMessage
        {
            ClientId = explicitClientId,
            User = new EndUser { KeyId = "explicit-user", CustomizedProperties = Array.Empty<CustomizedProperty>() },
            EnvId = Guid.NewGuid()
        };

        _mockBaseManager
            .Setup(x => x.HandleClientIdentifyAsync(connectionId, explicitMessage))
            .ReturnsAsync(new ClientIdentifyResponse { Success = true, ClientId = explicitClientId });

        // Act
        var result = await _enhancedManager.HandleClientIdentifyAsync(connectionId, explicitMessage);

        // Assert
        Assert.True(result.Success);
        Assert.Equal(explicitClientId, result.ClientId);
        Assert.False(_enhancedManager.IsAutoIdentified(connectionId)); // Should be removed from auto tracking
    }

