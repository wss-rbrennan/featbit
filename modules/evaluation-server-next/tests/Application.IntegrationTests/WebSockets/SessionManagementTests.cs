    private static IServiceProvider CreateTestServices()
    {
        var services = new ServiceCollection();
        
        // Mock Redis client session store
        var mockSessionStore = new Mock<IClientSessionStore>();
        var sessions = new ConcurrentDictionary<string, ClientSession>();
        
        mockSessionStore.Setup(x => x.CreateOrUpdateSessionAsync(It.IsAny<EndUser>(), It.IsAny<Guid>(), It.IsAny<string>(), It.IsAny<string>()))
            .ReturnsAsync((EndUser user, Guid envId, string connectionId, string serverId) =>
            {
                var clientId = $"legacy:client:test123:env:{envId:N}";
                var session = new ClientSession
                {
                    ClientId = clientId,
                    User = user,
                    EnvId = envId,
                    CurrentConnectionId = connectionId,
                    ServerId = serverId,
                    CreatedAt = DateTime.UtcNow,
                    LastSeen = DateTime.UtcNow,
                    SubscribedChannels = new List<string>()
                };
                sessions[clientId] = session;
                return clientId;
            });

        mockSessionStore.Setup(x => x.GetSessionAsync(It.IsAny<string>()))
            .ReturnsAsync((string clientId) => sessions.TryGetValue(clientId, out var session) ? session : null);

        mockSessionStore.Setup(x => x.AddChannelSubscriptionAsync(It.IsAny<string>(), It.IsAny<string>()))
            .ReturnsAsync((string clientId, string channel) =>
            {
                if (sessions.TryGetValue(clientId, out var session))
                {
                    session.SubscribedChannels.Add(channel);
                    return true;
                }
                return false;
            });

        // Mock subscription manager
        var mockSubscriptionManager = new Mock<ISubscriptionManager>();
        mockSubscriptionManager.Setup(x => x.AddChannelToSubscription(It.IsAny<string>(), It.IsAny<string>()));
        mockSubscriptionManager.Setup(x => x.RemoveChannelFromSubscription(It.IsAny<string>(), It.IsAny<string>()));
        mockSubscriptionManager.Setup(x => x.RemoveSubscription(It.IsAny<string>()));

        // Mock service identity provider
        var mockServiceIdentity = new Mock<IServiceIdentityProvider>();
        mockServiceIdentity.Setup(x => x.ServiceId).Returns("test-server-1");

        // Register services
        services.AddSingleton(mockSessionStore.Object);
        services.AddSingleton(mockSubscriptionManager.Object);
        services.AddSingleton(mockServiceIdentity.Object);
        services.AddLogging();
        
        // Add session management services
        services.AddScoped<IClientSessionManager, ClientSessionManager>();
        services.AddLegacyClientSessionManagement();

        return services.BuildServiceProvider();
    }

