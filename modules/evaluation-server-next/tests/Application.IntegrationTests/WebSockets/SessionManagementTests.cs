    [Fact]
    public async Task EnhancedSessionManager_HandlesConcurrentConnections()
    {
        // Arrange
        var services = CreateTestServices();
        var enhancedManager = services.GetRequiredService<IEnhancedClientSessionManager>();

        var tasks = new List<Task<AutoIdentifyResponse>>();

        // Act - Create 10 concurrent connections
        for (int i = 0; i < 10; i++)
        {
            var connectionId = $"conn-{i}";
            var connectionContext = CreateMockConnectionContext("client", $"user-{i}");
            tasks.Add(enhancedManager.HandleConnectionAsync(connectionId, connectionContext));
        }

        var responses = await Task.WhenAll(tasks);

        // Assert
        Assert.All(responses, response => Assert.True(response.Success));
        var clientIds = responses.Select(r => r.ClientId).ToList();
        Assert.Equal(10, clientIds.Distinct().Count()); // All unique client IDs
    }

